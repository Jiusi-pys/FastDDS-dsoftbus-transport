"""Delivery-only contract tests; no compiler, SDK call, or device execution."""
import importlib.util
import copy
import json
import os
from pathlib import Path
import tarfile
import tempfile
import unittest

ENTRY = Path(__file__).resolve().parents[1] / 'checkpoint_build.py'
spec = importlib.util.spec_from_file_location('checkpoint_build', ENTRY)
entry = importlib.util.module_from_spec(spec)
spec.loader.exec_module(entry)


class DeliveryContracts(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.base = Path(self.temp.name)

    def source_receipt(self):
        source = self.base / 'source'
        source.mkdir()
        (source / 'CMakeLists.txt').write_text('cmake_minimum_required(VERSION 3.22)\n')
        receipt = {'schema': 1, 'kind': 'RESTORED_PROJECT_SOURCE',
                   'source_root': str(source), 'baseline_head': 'a' * 40,
                   'checkpoint_inventory_sha256': 'b' * 64,
                   'overlay_manifest_sha256': 'c' * 64,
                   'files': [{'path': 'CMakeLists.txt', 'sha256': entry.hash_file(source / 'CMakeLists.txt'),
                              'origin': 'CHECKPOINT'}]}
        return source, receipt

    def test_source_hash_valid(self):
        source, receipt = self.source_receipt()
        self.assertEqual(entry.validate_source(receipt, source), 1)

    def test_source_hash_drift_rejected(self):
        source, receipt = self.source_receipt()
        (source / 'CMakeLists.txt').write_text('changed')
        with self.assertRaisesRegex(ValueError, 'hash'):
            entry.validate_source(receipt, source)

    def test_undeclared_live_source_rejected(self):
        source, receipt = self.source_receipt()
        (source / 'not-sealed.cpp').write_text('extra')
        with self.assertRaisesRegex(ValueError, 'undeclared source'):
            entry.validate_source(receipt, source)

    def test_only_declared_build_root_is_excluded(self):
        source, receipt = self.source_receipt()
        (source / '.artifacts').mkdir()
        (source / '.artifacts' / 'secret.cpp').write_text('extra')
        with self.assertRaisesRegex(ValueError, 'undeclared source'):
            entry.validate_source(receipt, source, [source / '.artifacts' / 'native-off'])

    def test_pycache_cannot_hide_unsealed_source(self):
        source, receipt = self.source_receipt()
        (source / '__pycache__').mkdir()
        (source / '__pycache__' / 'unsealed.py').write_text('not generated bytecode')
        with self.assertRaisesRegex(ValueError, 'undeclared source'):
            entry.validate_source(receipt, source)

    def test_exact_generated_fixture_acceptance_is_hash_bound(self):
        source, receipt = self.source_receipt()
        fixture = source / '.artifacts/build-input-tests' / ('a' * 32) / 'space name.h'
        fixture.parent.mkdir(parents=True)
        fixture.write_bytes(b'owned fixture')
        generated = [{'path': fixture.relative_to(source).as_posix(), 'sha256': entry.hash_file(fixture)}]
        self.assertEqual(entry.validate_source(receipt, source, generated_files=generated), 1)
        fixture.write_bytes(b'changed source')
        with self.assertRaisesRegex(ValueError, 'generated.*hash'):
            entry.validate_source(receipt, source, generated_files=generated)

    def test_unknown_artifact_is_not_covered_by_known_fixture(self):
        source, receipt = self.source_receipt()
        fixture = source / '.artifacts/build-input-tests' / ('a' * 32) / 'space name.h'
        fixture.parent.mkdir(parents=True)
        fixture.write_bytes(b'owned fixture')
        (fixture.parent / 'unsealed.cpp').write_bytes(b'unknown')
        generated = [{'path': fixture.relative_to(source).as_posix(), 'sha256': entry.hash_file(fixture)}]
        with self.assertRaisesRegex(ValueError, 'undeclared source'):
            entry.validate_source(receipt, source, generated_files=generated)

    def test_capture_generated_fixtures_requires_sealed_creators(self):
        source, receipt = self.source_receipt()
        fixture = source / '.artifacts/build-input-tests' / ('a' * 32) / 'space name.h'
        fixture.parent.mkdir(parents=True)
        fixture.write_bytes(b'owned fixture')
        with self.assertRaisesRegex(ValueError, 'creator'):
            entry.capture_generated_test_files(receipt, source)

    def test_source_receipt_wrong_root(self):
        source, receipt = self.source_receipt()
        with self.assertRaisesRegex(ValueError, 'root'):
            entry.validate_source(receipt, self.base / 'other')

    def test_source_path_traversal(self):
        source, receipt = self.source_receipt()
        receipt['files'][0]['path'] = '../escape.cpp'
        with self.assertRaises(ValueError):
            entry.validate_source(receipt, source)

    def test_source_duplicate_case_path(self):
        source, receipt = self.source_receipt()
        receipt['files'].append({**receipt['files'][0], 'path': 'CMAKELISTS.TXT'})
        with self.assertRaisesRegex(ValueError, 'collision'):
            entry.validate_source(receipt, source)

    def test_output_workspace_overlap(self):
        with self.assertRaisesRegex(ValueError, 'overlap'):
            entry.validate_output(self.base / 'source' / 'out', [self.base / 'source'])

    def test_output_parent_overlap(self):
        with self.assertRaisesRegex(ValueError, 'overlap'):
            entry.validate_output(self.base, [self.base / 'source'])

    def test_output_existing_unowned_rejected(self):
        with self.assertRaisesRegex(ValueError, 'existing'):
            entry.validate_output(self.base, [])

    def test_overlay_bad_hash(self):
        overlay = self.base / 'overlay'
        overlay.mkdir()
        (overlay / 'scripts').mkdir()
        (overlay / 'scripts/build.ps1').write_text('safe')
        manifest = {'schema': 1, 'files': [{'path': 'scripts/build.ps1', 'sha256': 'f' * 64}]}
        with self.assertRaisesRegex(ValueError, 'hash'):
            entry.read_overlay(overlay, manifest)

    def test_overlay_escape(self):
        with self.assertRaises(ValueError):
            entry.read_overlay(self.base, {'schema': 1, 'files': [{'path': '../escape', 'sha256': 'f' * 64}]})

    def test_archive_symlink_rejected(self):
        member = tarfile.TarInfo('src/link')
        member.type = tarfile.SYMTYPE
        member.linkname = '../../elsewhere'
        with self.assertRaisesRegex(ValueError, 'archive'):
            entry.validate_archive_members([member])

    def test_archive_traversal_rejected(self):
        with self.assertRaises(ValueError):
            entry.validate_archive_members([tarfile.TarInfo('../outside')])

    def test_runtime_cpp_overlay_rejected(self):
        overlay = self.base / 'overlay'
        (overlay / 'src').mkdir(parents=True)
        path = overlay / 'src' / 'ProcessCoordinator.cpp'
        path.write_text('changed')
        with self.assertRaisesRegex(ValueError, 'delivery scope'):
            entry.read_overlay(overlay, {'schema': 1, 'files': [{'path': 'src/ProcessCoordinator.cpp', 'sha256': entry.hash_file(path)}]})

    def test_native_review_source_identity(self):
        receipt = {'schema': 1, 'status': 'CLOSED', 'blocking_findings': 0,
                   'source_receipt_sha256': 'a' * 64,
                   'host_off': {'status': 'PASS'}, 'host_on': {'status': 'PASS'}}
        entry.validate_review(receipt, 'a' * 64)
        with self.assertRaisesRegex(ValueError, 'source'):
            entry.validate_review(receipt, 'b' * 64)

    def test_native_review_host_not_pass(self):
        receipt = {'schema': 1, 'status': 'CLOSED', 'blocking_findings': 0,
                   'source_receipt_sha256': 'a' * 64,
                   'host_off': {'status': 'PASS'}, 'host_on': {'status': 'NOT_RUN'}}
        with self.assertRaisesRegex(ValueError, 'host'):
            entry.validate_review(receipt, 'a' * 64)

    def test_native_executable_is_never_run(self):
        config = {'powershell': 'C:/Windows/powershell.exe', 'native': {
            'sdk_root': 'C:/sdk', 'prefix': 'C:/prefix', 'platform_compiler': 'C:/clang++.exe',
            'token_setproc_library': 'C:/tokens.so', 'access_token_library': 'C:/access.so',
            'platform_cxx_library': 'C:/cxx.so'}}
        command = entry.native_command(config, self.base / 'source', self.base / 'receipt.json', 'on')
        self.assertEqual(command[0], config['powershell'])
        self.assertIn('-EnableRxDrop', command)
        self.assertIn(str(self.base / 'source' / '.artifacts/reference/security_access_token'), command)
        self.assertFalse(any('hdc' in str(item) for item in command))

    def test_host_recipe_preserves_canonical_capability_probe(self):
        config = {'cmake': 'C:/cmake.exe', 'python': 'C:/python.exe', 'node': 'C:/node.exe',
                  'powershell': 'C:/powershell.exe', 'host': {'prefix': 'C:/host-prefix'}}
        configure, build = entry.host_commands(config, self.base / 'src', self.base / 'build', 'off')
        # Recorded independent-r1 full148/150 Host recipe has this ON.
        self.assertIn('-DBUILD_SOFTBUS_CAPABILITY_PROBE=ON', configure)
        self.assertIn('-DMDDS_EXPERIMENT_NATIVE=OFF', configure)
        self.assertIn('-DCMAKE_CONFIGURATION_TYPES=Release', configure)


class ActualDependencySelectionContracts(unittest.TestCase):
    """Exercise the real preflight on pinned local declarations; never run a selected executable."""
    @classmethod
    def setUpClass(cls):
        declared = os.environ.get('MDDS_CHECKPOINT_TEST_DECLARATIONS')
        if not declared:
            raise ValueError('MDDS_CHECKPOINT_TEST_DECLARATIONS must explicitly name the read-only external test declaration JSON')
        cls.config_path = Path(declared)
        if not cls.config_path.is_absolute():
            raise ValueError('MDDS_CHECKPOINT_TEST_DECLARATIONS must be an absolute path')
        cls.config = entry.read_json(cls.config_path)
        cls.config['_config_sha256'] = entry.hash_file(cls.config_path)
        cls.checkpoint = Path(cls.config['checkpoint_tool']['path']).parent / 'final-bundle'

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.base = Path(self.temp.name)

    def rejection(self, section, key, replacement):
        config = copy.deepcopy(self.config)
        config[section][key] = replacement
        output = self.base / ('absent-' + key)
        with self.assertRaisesRegex(ValueError, 'declared|inconsistent|ABI|configuration'):
            entry.preflight(config, self.checkpoint, output)
        self.assertFalse(output.exists(), 'failed preflight must not create output or run compiler')

    def test_final_declared_config_is_valid_without_side_effects(self):
        output = self.base / 'valid-dry-run'
        result = entry.preflight(self.config, self.checkpoint, output)
        self.assertEqual(result['status'], 'PREFLIGHT_PASS')
        self.assertEqual(result['declared_unique_files'], 2242)
        self.assertFalse(output.exists())

    def test_native_compiler_substitution_rejected_before_side_effects(self):
        self.rejection('native', 'platform_compiler', 'C:/Windows/System32/notepad.exe')

    def test_each_native_library_substitution_rejected_before_side_effects(self):
        for key in ('token_setproc_library', 'access_token_library', 'platform_cxx_library'):
            with self.subTest(key=key):
                self.rejection('native', key, 'C:/Windows/System32/notepad.exe')

    def test_sdk_root_substitution_rejected_before_side_effects(self):
        self.rejection('native', 'sdk_root', 'C:/Windows/System32')

    def test_native_prefix_substitution_rejected_before_side_effects(self):
        self.rejection('native', 'prefix', 'C:/Windows/System32')

    def test_host_prefix_substitution_rejected_before_side_effects(self):
        self.rejection('host', 'prefix', 'C:/Windows/System32')

    def test_ignored_host_config_path_is_rejected(self):
        self.rejection('host', 'fastdds_dir', 'C:/Windows/System32')

    def test_ignored_native_ninja_is_rejected(self):
        self.rejection('native', 'ninja', 'C:/Windows/System32/notepad.exe')


