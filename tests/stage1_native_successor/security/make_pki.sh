#!/bin/bash
# Test-only DDS Security PKI for the device feature matrix (not secret, not for production).
set -e
O=/c/pixi_ws/.pixi/envs/default/Library/bin/openssl.exe
D=$1; mkdir -p "$D"; cd "$D"
cat > template.cnf <<'EOF'
[req]
distinguished_name=dn
prompt=no
[dn]
CN=fdds_dsb_test_ca
O=FastDDS-DSoftBus-Test
[v3_ca]
basicConstraints=critical,CA:TRUE
keyUsage=critical,keyCertSign,cRLSign
subjectKeyIdentifier=hash
EOF
export OPENSSL_CONF="$(pwd -W 2>/dev/null || pwd)/template.cnf"
mk_ca(){ # name cn
  $O ecparam -name prime256v1 -genkey -noout -out $1_key.pem
  sed "s/CN=fdds_dsb_test_ca/CN=$2/" template.cnf > $1.cnf
  $O req -new -x509 -sha256 -days 3650 -key $1_key.pem -out $1.pem -config $1.cnf -extensions v3_ca
}
mk_id(){ # name cn ca
  $O ecparam -name prime256v1 -genkey -noout -out $1_key.pem
  $O req -new -sha256 -key $1_key.pem -out $1.csr -subj "/CN=$2/O=FastDDS-DSoftBus-Test"
  $O x509 -req -sha256 -days 3650 -in $1.csr -CA $3.pem -CAkey $3_key.pem -CAcreateserial -out $1.pem
}
mk_ca ca fdds_dsb_test_ca
mk_ca rogue_ca fdds_dsb_rogue_ca
mk_id id0 fdds_dsb_side0 ca
mk_id id1 fdds_dsb_side1 ca
mk_id rogue1 fdds_dsb_side1 rogue_ca
cat > governance.xml <<'EOF'
<?xml version="1.0" encoding="UTF-8"?>
<dds xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="omg_shared_ca_governance.xsd">
  <domain_access_rules>
    <domain_rule>
      <domains><id_range><min>0</min><max>230</max></id_range></domains>
      <allow_unauthenticated_participants>false</allow_unauthenticated_participants>
      <enable_join_access_control>true</enable_join_access_control>
      <discovery_protection_kind>ENCRYPT</discovery_protection_kind>
      <liveliness_protection_kind>ENCRYPT</liveliness_protection_kind>
      <rtps_protection_kind>ENCRYPT</rtps_protection_kind>
      <topic_access_rules>
        <topic_rule>
          <topic_expression>*</topic_expression>
          <enable_discovery_protection>true</enable_discovery_protection>
          <enable_liveliness_protection>true</enable_liveliness_protection>
          <enable_read_access_control>true</enable_read_access_control>
          <enable_write_access_control>true</enable_write_access_control>
          <metadata_protection_kind>ENCRYPT</metadata_protection_kind>
          <data_protection_kind>ENCRYPT</data_protection_kind>
        </topic_rule>
      </topic_access_rules>
    </domain_rule>
  </domain_access_rules>
</dds>
EOF
mk_perm(){ # side cn
cat > permissions$1.xml <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<dds xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="omg_shared_ca_permissions.xsd">
  <permissions>
    <grant name="fdds_dsb_grant_$1">
      <subject_name>CN=$2,O=FastDDS-DSoftBus-Test</subject_name>
      <validity><not_before>2026-01-01T00:00:00</not_before><not_after>2036-01-01T00:00:00</not_after></validity>
      <deny_rule>
        <domains><id_range><min>0</min><max>230</max></id_range></domains>
        <publish><topics><topic>*_f_sec_denied</topic></topics></publish>
      </deny_rule>
      <allow_rule>
        <domains><id_range><min>0</min><max>230</max></id_range></domains>
        <publish><topics><topic>*</topic></topics></publish>
        <subscribe><topics><topic>*</topic></topics></subscribe>
      </allow_rule>
      <default>DENY</default>
    </grant>
  </permissions>
</dds>
EOF
$O smime -sign -text -in permissions$1.xml -out permissions$1.p7s -signer ca.pem -inkey ca_key.pem
}
mk_perm 0 fdds_dsb_side0
mk_perm 1 fdds_dsb_side1
$O smime -sign -text -in governance.xml -out governance.p7s -signer ca.pem -inkey ca_key.pem
$O verify -CAfile ca.pem id0.pem id1.pem
$O verify -CAfile ca.pem rogue1.pem || echo "rogue1 not trusted by ca (expected)"
# C++ header with raw string literals (test material only)
H=security_pki.hpp
{ echo '#pragma once'; echo '// Test-only DDS Security PKI generated by make_pki.sh. Not secret; never use in production.'; echo '#include <utility>'; echo 'namespace stage1_pki {'; echo 'static const std::pair<const char*,const char*> kFiles[]={'
  for f in ca.pem id0.pem id0_key.pem id1.pem id1_key.pem rogue1.pem rogue1_key.pem governance.p7s permissions0.p7s permissions1.p7s; do
    echo "    {\"$f\",R\"PKI($(cat $f))PKI\"},"; done
  echo '};'; echo '} // namespace stage1_pki'; } > $H
echo done
